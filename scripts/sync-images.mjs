// Scans src/assets/images/products for real product photos and writes src/app/data/image-manifest.ts
// File naming: <slug>.webp|jpg|jpeg|png|avif  (main image), <slug>-2.webp, <slug>-3.webp ... (gallery)
import fs from 'fs';
const dir = 'src/assets/images/products';
const files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
const map = {};
for (const f of files.sort()) {
  const m = f.match(/^(.+?)(?:-(\d))?\.(webp|jpe?g|png|avif)$/i);
  if (!m) continue;
  const slug = m[1];
  (map[slug] ??= []).push(f);
}
// main image first
for (const k of Object.keys(map)) map[k].sort((a, b) => (/-\d\./.test(a) ? 1 : 0) - (/-\d\./.test(b) ? 1 : 0) || a.localeCompare(b));
fs.writeFileSync('src/app/data/image-manifest.ts',
`// AUTO-GENERATED by scripts/sync-images.mjs. Do not edit by hand.
// Lists real product photos found in src/assets/images/products (slug -> file names).
export const PHOTO_FILES: Record<string, string[]> = ${JSON.stringify(map, null, 2)};
`);
console.log(`Image manifest: ${Object.keys(map).length} product(s) with photos.`);
